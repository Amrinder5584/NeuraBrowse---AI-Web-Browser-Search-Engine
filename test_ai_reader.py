import pytest

import ai as ai_mod
import reader
from ai import AIError, ClaudeAI, OfflineAI, answer_with_fallback, get_ai

RESULTS = [
    {"title": "Flask Documentation", "url": "https://flask.palletsprojects.com/",
     "snippet": "Flask is a lightweight Python web framework. It is easy to start."},
    {"title": "Real Python", "url": "https://realpython.com/", "snippet": "Python tutorials."},
]


def test_offline_ai_names_best_site_and_is_honest():
    text = OfflineAI().answer("flask", RESULTS)
    assert "Flask Documentation" in text
    assert "not generated by a language model" in text


def test_offline_ai_handles_no_results():
    assert "could not find" in OfflineAI().answer("zzz", []).lower()


def test_offline_summarize_picks_long_sentences():
    page = "Short. " + "This is a reasonably long sentence about databases and storage. " * 3
    assert OfflineAI().summarize("t", page).startswith("- This is")


def test_get_ai_selects_by_key():
    assert get_ai({"ANTHROPIC_API_KEY": None}).mode == "offline"
    assert get_ai({"ANTHROPIC_API_KEY": "k", "AI_MODEL": "m", "AI_MAX_TOKENS": 10}).mode == "claude"


def test_fallback_when_model_fails():
    class Failing:
        mode = "claude"

        def answer(self, *a, **k):
            raise AIError("boom")

    text, mode, degraded = answer_with_fallback(Failing(), "flask", RESULTS)
    assert mode == "offline" and degraded is True and "Flask" in text


def test_claude_ai_builds_request(monkeypatch):
    captured = {}

    class FakeResp:
        def raise_for_status(self):
            pass

        def json(self):
            return {"content": [{"type": "text", "text": "Hello [1]"}]}

    def fake_post(url, headers, json, timeout):
        captured.update(url=url, headers=headers, json=json)
        return FakeResp()

    monkeypatch.setattr(ai_mod.requests, "post", fake_post)
    out = ClaudeAI("key123", "some-model", 100).answer("what is flask", RESULTS)
    assert out == "Hello [1]"
    assert captured["headers"]["x-api-key"] == "key123"
    assert captured["json"]["model"] == "some-model"
    assert "Flask Documentation" in captured["json"]["messages"][-1]["content"]


# --------------------------------------------------------------------------- reader / SSRF
@pytest.mark.parametrize("url", [
    "http://127.0.0.1/", "http://localhost:5000/", "http://169.254.169.254/latest/meta-data/",
    "http://10.0.0.5/", "file:///etc/passwd", "ftp://example.com/", "javascript:alert(1)",
    "http://[::1]/",
])
def test_unsafe_urls_rejected(url):
    assert reader.is_safe_url(url) is False


def test_extract_readable_strips_scripts_and_menus():
    html = """<html><head><title> My  Page </title><script>var secret=1;</script></head>
    <body><nav>Home About Contact us today for stuff</nav>
    <p>This paragraph has plenty of real readable words in it.</p>
    <style>.x{color:red}</style><footer>Copyright footer text that is long enough</footer></body></html>"""
    title, text = reader.extract_readable(html)
    assert title == "My Page"
    assert "readable words" in text
    assert "secret" not in text and "Copyright" not in text and "Home About" not in text
