"""AI layer.

* ClaudeAI   - real LLM answers through the Anthropic Messages API (needs ANTHROPIC_API_KEY).
* OfflineAI  - no model: extractive summaries built from the search results. It keeps the
               app usable without a key, but it is NOT a language model and says so.

`answer_with_fallback` tries the configured AI and falls back to OfflineAI on any error.
"""
import re

import requests

API_URL = "https://api.anthropic.com/v1/messages"
API_VERSION = "2023-06-01"

SYSTEM_PROMPT = (
    "You are the assistant inside NeuraBrowse, an AI web browser. You are given a user "
    "question and a numbered list of search results. Answer concisely in 3-6 sentences "
    "using the results, cite them like [1] or [2], and finish with one line starting "
    "'Best site:' naming the single most useful result and why. If the results do not "
    "contain the answer, say so instead of guessing."
)


class AIError(Exception):
    pass


def _sources_block(results, limit=6):
    lines = []
    for i, r in enumerate(results[:limit], 1):
        lines.append(f"[{i}] {r['title']} ({r['url']})\n    {r['snippet']}")
    return "\n".join(lines)


def _first_sentence(text, max_len=220):
    text = re.sub(r"\s+", " ", text or "").strip()
    match = re.match(r"(.+?[.!?])(\s|$)", text)
    sentence = match.group(1) if match else text
    return sentence[:max_len]


# --------------------------------------------------------------------------- real model
class ClaudeAI:
    mode = "claude"

    def __init__(self, api_key, model, max_tokens=700, timeout=30):
        self.api_key, self.model = api_key, model
        self.max_tokens, self.timeout = max_tokens, timeout

    def _call(self, system, messages):
        try:
            resp = requests.post(
                API_URL,
                headers={"x-api-key": self.api_key, "anthropic-version": API_VERSION,
                         "content-type": "application/json"},
                json={"model": self.model, "max_tokens": self.max_tokens,
                      "system": system, "messages": messages},
                timeout=self.timeout,
            )
            resp.raise_for_status()
            blocks = resp.json().get("content", [])
            text = "".join(b.get("text", "") for b in blocks if b.get("type") == "text").strip()
        except Exception as exc:
            raise AIError(str(exc)) from exc
        if not text:
            raise AIError("empty response from model")
        return text

    def answer(self, query, results, history=None):
        messages = [m for m in (history or [])[-6:] if m.get("role") in ("user", "assistant")]
        content = f"Question: {query}\n\nSearch results:\n{_sources_block(results)}"
        messages.append({"role": "user", "content": content})
        return self._call(SYSTEM_PROMPT, messages)

    def summarize(self, title, text):
        prompt = f"Summarize this web page in 4-5 bullet points.\n\nTitle: {title}\n\n{text[:12000]}"
        return self._call("You summarize web pages accurately and briefly.",
                          [{"role": "user", "content": prompt}])


# --------------------------------------------------------------------------- no-model fallback
class OfflineAI:
    mode = "offline"

    def answer(self, query, results, history=None):
        if not results:
            return ("I could not find anything for that. Try different or fewer keywords, "
                    "or check your internet connection.")
        best, rest = results[0], results[1:3]
        summary = " ".join(_first_sentence(r["snippet"]) for r in results[:2] if r["snippet"])
        lines = [f"Here is what the top results say about \"{query}\":", summary or best["title"],
                 "", f"**Best site:** {best['title']} - {best['url']}"]
        if rest:
            lines.append("**Also useful:** " + "; ".join(r["title"] for r in rest))
        lines.append("(Offline mode: this summary is extracted from search results, "
                     "not generated by a language model.)")
        return "\n".join(lines)

    def summarize(self, title, text):
        sentences = re.split(r"(?<=[.!?])\s+", re.sub(r"\s+", " ", text).strip())
        picked = [s for s in sentences if len(s) > 40][:5]
        if not picked:
            return "This page has too little readable text to summarize."
        return "\n".join(f"- {s}" for s in picked)


# --------------------------------------------------------------------------- factory
def get_ai(config):
    if config.get("ANTHROPIC_API_KEY"):
        return ClaudeAI(config["ANTHROPIC_API_KEY"], config["AI_MODEL"], config["AI_MAX_TOKENS"])
    return OfflineAI()


def answer_with_fallback(ai, query, results, history=None):
    """Returns (text, mode, degraded)."""
    try:
        return ai.answer(query, results, history), ai.mode, False
    except AIError:
        return OfflineAI().answer(query, results, history), "offline", True


def summarize_with_fallback(ai, title, text):
    try:
        return ai.summarize(title, text), ai.mode, False
    except AIError:
        return OfflineAI().summarize(title, text), "offline", True
